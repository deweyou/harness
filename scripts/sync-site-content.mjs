import { access, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import yaml from 'js-yaml';

const GITHUB_SOURCE_BASE = 'https://github.com/deweyou/agents/blob/main';
const generatedMarker = '<!-- Generated by scripts/sync-site-content.mjs. Do not edit directly. -->';

const skillOrder = [
  'repo-memory',
  'git-delivery',
  'spec-driven-coding',
  'skill-eval',
  'product-notes',
  'ui-design',
  'product-design',
];

const ruleOrder = ['collaboration-defaults', 'code-style', 'engineering-principles'];
const designOrder = ['dewey-interface'];

export async function discoverSiteAssets(repositoryRoot) {
  const skills = await Promise.all(
    skillOrder.map(async (name) => {
      const skillRoot = path.join(repositoryRoot, 'skills', name);
      const skillMarkdown = await readFile(path.join(skillRoot, 'SKILL.md'), 'utf8');
      const { frontmatter } = parseFrontmatter(skillMarkdown);
      const englishReadme = path.posix.join('skills', name, 'README.md');
      const chineseReadme = path.posix.join('skills', name, 'README_ZH.md');

      return {
        name,
        description: normalizeDescription(frontmatter.description),
        hasEnglish: await fileExists(path.join(repositoryRoot, englishReadme)),
        hasChinese: await fileExists(path.join(repositoryRoot, chineseReadme)),
        englishReadme,
        chineseReadme,
        source: path.posix.join('skills', name, 'SKILL.md'),
      };
    }),
  );

  return {
    skills,
    rules: await discoverFrontmatterAssets(repositoryRoot, 'rules', ruleOrder),
    designs: await discoverFrontmatterAssets(repositoryRoot, 'design', designOrder),
  };
}

export function rewriteMarkdownLinks(markdown, sourceDirectory) {
  return markdown.replace(/(!?\[[^\]]*?\]\()([^)\s]+)(\))/g, (fullMatch, linkStart, linkTarget, linkEnd) => {
    if (!shouldRewriteLink(linkTarget)) {
      return fullMatch;
    }

    const [targetPath, suffix = ''] = splitLinkSuffix(linkTarget);
    const normalizedTarget = normalizeRepositoryTarget(sourceDirectory, targetPath);
    const rewrittenTarget = rewriteRepositoryTarget(normalizedTarget);

    return `${linkStart}${rewrittenTarget}${suffix}${linkEnd}`;
  });
}

export async function buildSiteContent({ repositoryRoot, siteRoot }) {
  const assets = await discoverSiteAssets(repositoryRoot);

  await removeGeneratedOutputs(siteRoot);

  await copyReadmePage({
    repositoryRoot,
    siteRoot,
    source: 'README.md',
    output: 'guide/index.md',
    title: 'Guide',
    description: 'Repository guide for the agents hub.',
  });
  await copyReadmePage({
    repositoryRoot,
    siteRoot,
    source: 'README_ZH.md',
    output: 'zh/guide/index.md',
    title: '指南',
    description: 'Agents hub 仓库指南。',
  });

  await writeGeneratedPage(
    path.join(siteRoot, 'skills/index.md'),
    createSkillIndex('en', assets.skills),
  );
  await writeGeneratedPage(
    path.join(siteRoot, 'zh/skills/index.md'),
    createSkillIndex('zh', assets.skills),
  );

  for (const skill of assets.skills) {
    if (skill.hasEnglish) {
      await copyReadmePage({
        repositoryRoot,
        siteRoot,
        source: skill.englishReadme,
        output: `skills/${skill.name}.md`,
        title: skill.name,
        description: skill.description,
      });
    }

    if (skill.hasChinese) {
      await copyReadmePage({
        repositoryRoot,
        siteRoot,
        source: skill.chineseReadme,
        output: `zh/skills/${skill.name}.md`,
        title: skill.name,
        description: skill.description,
      });
    }
  }

  await writeGeneratedPage(
    path.join(siteRoot, 'rules/index.md'),
    createAssetIndex({
      title: 'Rules',
      intro: 'Reusable passive preferences and constraints for agent work.',
      assets: assets.rules,
    }),
  );
  await writeGeneratedPage(
    path.join(siteRoot, 'zh/rules/index.md'),
    createAssetIndex({
      title: 'Rules',
      intro: '跨项目复用的被动偏好和约束。',
      assets: assets.rules,
    }),
  );
  await writeGeneratedPage(
    path.join(siteRoot, 'design/index.md'),
    createAssetIndex({
      title: 'Design',
      intro: 'Reusable interface design contracts for AI-assisted UI work.',
      assets: assets.designs,
    }),
  );
  await writeGeneratedPage(
    path.join(siteRoot, 'zh/design/index.md'),
    createAssetIndex({
      title: 'Design',
      intro: '用于 AI 辅助 UI 工作的可复用界面设计契约。',
      assets: assets.designs,
    }),
  );
  await writeGeneratedPage(path.join(siteRoot, 'cli/index.md'), createCliPage('en'));
  await writeGeneratedPage(path.join(siteRoot, 'zh/cli/index.md'), createCliPage('zh'));

  await mkdir(path.join(siteRoot, '.vitepress/generated'), { recursive: true });
  await writeFile(
    path.join(siteRoot, '.vitepress/generated/assets.json'),
    `${JSON.stringify(assets, null, 2)}\n`,
    'utf8',
  );
}

function parseFrontmatter(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---\n?/);

  if (!match) {
    return { frontmatter: {}, body: markdown };
  }

  return {
    frontmatter: yaml.load(match[1]) ?? {},
    body: markdown.slice(match[0].length),
  };
}

async function discoverFrontmatterAssets(repositoryRoot, directory, preferredOrder) {
  const discoveredFiles = await readdir(path.join(repositoryRoot, directory));
  const discoveredNames = discoveredFiles
    .filter((fileName) => fileName.endsWith('.md'))
    .map((fileName) => fileName.replace(/\.md$/, ''));
  const orderedNames = [
    ...preferredOrder.filter((name) => discoveredNames.includes(name)),
    ...discoveredNames.filter((name) => !preferredOrder.includes(name)).sort(),
  ];

  return Promise.all(
    orderedNames.map(async (name) => {
      const source = path.posix.join(directory, `${name}.md`);
      const markdown = await readFile(path.join(repositoryRoot, source), 'utf8');
      const { frontmatter } = parseFrontmatter(markdown);

      return {
        name: frontmatter.name ?? name,
        description: normalizeDescription(frontmatter.description),
        source,
      };
    }),
  );
}

function normalizeDescription(description) {
  return String(description ?? '').replace(/\s+/g, ' ').trim();
}

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

function shouldRewriteLink(linkTarget) {
  return !/^(?:[a-z][a-z\d+.-]*:|#)/i.test(linkTarget);
}

function splitLinkSuffix(linkTarget) {
  const match = linkTarget.match(/^([^?#]*)([?#].*)?$/);
  return [match?.[1] ?? linkTarget, match?.[2] ?? ''];
}

function normalizeRepositoryTarget(sourceDirectory, linkTarget) {
  const normalizedSource = sourceDirectory.replaceAll(path.sep, '/');
  return path.posix.normalize(path.posix.join(normalizedSource, linkTarget));
}

function rewriteRepositoryTarget(normalizedTarget) {
  const target = normalizedTarget.replace(/^\.\//, '');

  if (target === 'skills') {
    return '/skills/';
  }

  if (target.startsWith('skills/') && target.endsWith('/')) {
    const skillName = target.split('/')[1];
    return `/skills/${skillName}`;
  }

  if (target.match(/^skills\/[^/]+\/README(?:_ZH)?\.md$/)) {
    const skillName = target.split('/')[1];
    return `/skills/${skillName}`;
  }

  return `${GITHUB_SOURCE_BASE}/${target}`;
}

function pageFrontmatter(title, description) {
  return `---\ntitle: ${yamlScalar(title)}\ndescription: ${yamlScalar(description)}\n---\n\n`;
}

function yamlScalar(value) {
  return yaml.dump(value, { lineWidth: -1 }).trimEnd();
}

async function writeGeneratedPage(filePath, content) {
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, insertGeneratedMarker(content), 'utf8');
}

function insertGeneratedMarker(content) {
  const frontmatterMatch = content.match(/^---\n[\s\S]*?\n---\n?/);

  if (!frontmatterMatch) {
    return `${generatedMarker}\n${content}`;
  }

  return `${frontmatterMatch[0].trimEnd()}\n\n${generatedMarker}\n${content.slice(frontmatterMatch[0].length)}`;
}

async function copyReadmePage({ repositoryRoot, siteRoot, source, output, title, description }) {
  const sourceMarkdown = await readFile(path.join(repositoryRoot, source), 'utf8');
  const body = rewriteMarkdownLinks(sourceMarkdown, path.posix.dirname(source));

  await writeGeneratedPage(
    path.join(siteRoot, output),
    `${pageFrontmatter(title, description)}${body}`,
  );
}

function createSkillIndex(locale, skills) {
  const heading = 'Skills';
  const intro =
    locale === 'zh'
      ? '可安装的主动 agent 工作流。每个页面来自对应 skill 的 README。'
      : 'Installable active agent workflows. Each page is generated from the skill README.';
  const rows = skills
    .map((skill) => `| [${skill.name}](./${skill.name}.md) | ${skill.description} |`)
    .join('\n');

  return `${pageFrontmatter(heading, intro)}# ${heading}\n\n${intro}\n\n| Skill | Description |\n| --- | --- |\n${rows}\n`;
}

function createAssetIndex({ title, intro, assets }) {
  const rows = assets
    .map(
      (asset) =>
        `| \`${asset.name}\` | ${asset.description} | [Source](${GITHUB_SOURCE_BASE}/${asset.source}) |`,
    )
    .join('\n');

  return `${pageFrontmatter(title, intro)}# ${title}\n\n${intro}\n\n| Asset | Description | Source |\n| --- | --- | --- |\n${rows}\n`;
}

function createCliPage(locale) {
  const title = 'CLI';
  const intro =
    locale === 'zh'
      ? '`deweyou-cli` 会把这个仓库中的 skills、rules 和 design contracts 接入其他本地仓库。'
      : '`deweyou-cli` wires skills, rules, and design contracts from this hub into other local repositories.';
  const docsLine =
    locale === 'zh'
      ? `阅读 [cli/README.md](${GITHUB_SOURCE_BASE}/cli/README.md) 中的包文档。`
      : `Read the package docs in [cli/README.md](${GITHUB_SOURCE_BASE}/cli/README.md).`;

  return `${pageFrontmatter(title, intro)}# ${title}\n\n${intro}\n\n\`\`\`bash\nnpm install -g deweyou-cli\ndeweyou-cli agent update\ndeweyou-cli agent init\ndeweyou-cli agent doctor\n\`\`\`\n\n${docsLine}\n`;
}

async function removeGeneratedOutputs(siteRoot) {
  const generatedDirectories = [
    'guide',
    'skills',
    'rules',
    'design',
    'cli',
    'zh/guide',
    'zh/skills',
    'zh/rules',
    'zh/design',
    'zh/cli',
    '.vitepress/generated',
  ];

  await Promise.all(
    generatedDirectories.map((directory) =>
      rm(path.join(siteRoot, directory), { recursive: true, force: true }),
    ),
  );
}

async function main() {
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

  await buildSiteContent({
    repositoryRoot,
    siteRoot: path.join(repositoryRoot, 'site'),
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
