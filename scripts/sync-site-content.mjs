async function removeGeneratedOutputs(siteRoot) {
  const generatedDirectories = [
    'guide',
    'ddev',
    'skills',
    'rules',
    'design',
    'cli',
    'zh/guide',
    'zh/ddev',
    'zh/skills',
    'zh/rules',
    'zh/design',
    'zh/cli',
    '.vitepress/generated',
  ];

  await Promise.all(
    generatedDirectories.map((directory) => rm(path.join(siteRoot, directory), { recursive: true, force: true })),
  );
}

async function main() {
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

  await buildSiteContent({
    repositoryRoot,
    siteRoot: path.join(repositoryRoot, 'site'),
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
