function createSkillIndex(locale, skills) {
  const heading = 'Skills';
  const intro =
    locale === 'zh'
      ? '可安装的主动 agent 工作流。DDev 项目默认只把 `ddev` 作为仓库入口，其余模块 skill 留在全局缓存并可按需单独安装。'
      : 'Installable active agent workflows. DDev projects install only the `ddev` entry skill by default; module skills stay in the global cache and remain independently installable.';
  const rows = skills
    .map((skill) => {
      const href = locale === 'zh' && !skill.hasChinese ? `/skills/${skill.name}` : `./${skill.name}.md`;
      const description = locale === 'zh' ? skill.chineseDescription : skill.description;

      return `| [${skill.name}](${href}) | ${description} |`;
    })
    .join('\n');

  return `${pageFrontmatter(heading, intro)}# ${heading}\n\n${intro}\n\n| Skill | Description |\n| --- | --- |\n${rows}\n`;
}

function createAssetIndex({ title, intro, assets, locale }) {
  const rows = assets
    .map((asset) => {
      const description = locale === 'zh' ? asset.chineseDescription : asset.description;
      const sourceLabel = locale === 'zh' ? '英文源文件' : 'Source';

      return `| [${asset.name}](./${asset.name}.md) | ${description} | [${sourceLabel}](${GITHUB_SOURCE_BASE}/${asset.source}) |`;
    })
    .join('\n');

  const headers = locale === 'zh' ? '| 资产 | 说明 | 英文源文件 |' : '| Asset | Description | Source |';

  return `${pageFrontmatter(title, intro)}# ${title}\n\n${intro}\n\n${headers}\n| --- | --- | --- |\n${rows}\n`;
}

